// Hapus semua tabel dalam urutan aman FK (anak dulu) - pakai ini di
// beforeEach/beforeAll integration & e2e test, jangan delete per tabel.
export async function truncateAll(db: AppDatabase): Promise<void> {
  await ensureTestDbReady();
  for (const table of [
    auditLogs,
    wordReports,
    bugReports,
    translationHelpReplies,
    translationHelps,
    contributionReviews,
    contributions,
    wordEditSuggestions,
    votes,
    commentBlocklistWords,
    comments,
    bookmarks,
    notificationCampaignRecipients,
    notificationCampaigns,
    notificationTemplates,
    notifications,
    deviceTokens,
    verifierApplications,
    lexicalRelations,
    pronunciations,
    wordAudios,
    examples,
    meaningTranslations,
    passwordResetTokens,
    accountDeletionTokens,
    refreshTokens,
    authIdentities,
    emailVerificationOtps,
    searchMisses,
    wordCategories,
    wordImages,
    wordVariants,
    meanings,
    words,
    categories,
    wordClasses,
    dialects,
    languages,
    users,
  ]) {
    await db.delete(table);
  }
}
